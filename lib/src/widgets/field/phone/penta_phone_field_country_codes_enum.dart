  const PentaPhoneFieldCountryCodesEnum(
    this.isoCode,
    this.dialCode,
    this.minLength,
    this.maxLength,
  );

  /// ISO 3166-1 alpha-2 code, e.g. `TR`.
  final String isoCode;

  /// International prefix including `+`, e.g. `+90`.
  final String dialCode;

  /// Allowed national number length (digits, without the dial code).
  final int minLength;
  final int maxLength;

  /// Emoji flag built from [isoCode].
  String get flag => String.fromCharCodes(
    isoCode.toUpperCase().codeUnits.map((c) => 0x1F1E6 + c - 0x41),
  );

  /// Localized country name; falls back to English.
  String countryName([String languageCode = 'en']) =>
      _PhoneFieldLanguageHelper.countryName(this, languageCode);

  /// Info object with the name in [languageCode].
  PentaPhoneFieldPhoneInfo info([String languageCode = 'en']) =>
      PentaPhoneFieldPhoneInfo(
        countryName: countryName(languageCode),
        countryCode: isoCode,
        dialCode: dialCode,
        flag: flag,
        minLength: minLength,
        maxLength: maxLength,
      );

  /// Country with the given ISO code (case-insensitive), or `null`.
  static PentaPhoneFieldCountryCodesEnum? fromIsoCode(String? isoCode) {
    if (isoCode == null) return null;
    final code = isoCode.toUpperCase();
    for (final country in values) {
      if (country.isoCode == code) return country;
    }
    return null;
  }
